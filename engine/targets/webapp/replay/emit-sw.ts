function isBackendDataPath(pathname) {
  return BACKEND_DATA_PATTERNS.some((re) => re.test(pathname));
}

/**
 * ADDITIVE backend proxy. Forwards a request to the OWNED local backend ONLY
 * when its path matches a routed internal-DATA endpoint (isBackendDataPath).
 * Returns the backend Response when it answers LIVE (x-backend:live); returns
 * null for non-data paths, a backend MISS (x-backend:miss or any non-live
 * answer), an empty body, or any network error — so the caller falls back to
 * the captured recording. Inert when BACKEND_URL is empty (no regression).
 */
async function tryBackend(request, url, method, bodyText) {
  if (!BACKEND_URL) return null;
  // Guard: only forward routed internal-data endpoints. Everything else (flags,
  // auth, telemetry, CDN) is left for the recording — the proxy never shadows it.
  if (!isBackendDataPath(url.pathname)) return null;
  let target;
  try {
    const base = new URL(BACKEND_URL);
    target = base.origin + url.pathname + url.search;
  } catch (err) {
    return null;
  }
  const init = {
    method,
    headers: { 'content-type': request.headers.get('content-type') || 'application/json' },
  };
  if (method !== 'GET' && method !== 'HEAD' && bodyText) init.body = bodyText;
  try {
    const res = await fetch(target, init);
    if (!res) return null;
    // Only a positive x-backend:live answer wins. miss / absent / anything else
    // falls back to the recording (defensive against a cross-origin header that
    // does not read back as exactly 'live').
    if (res.headers.get('x-backend') !== 'live') return null;
    const body = await res.text();
    // An empty/degenerate body is not real data; let the recording answer.
    if (!body || body === '{}' || body === '[]') return null;
    SERVED_BACKEND++;
    return new Response(body, {
      status: res.status,
      headers: {
        'content-type': res.headers.get('content-type') || 'application/json',
        'x-replay-source': 'backend',
        'x-backend': 'live',
      },
    });
  } catch (err) {
    return null;
  }
}

function recordedResponse(rec) {
  SERVED_RECORDING++;
  return new Response(rec.body, {
    status: rec.status,
    headers: {
      'content-type': rec.contentType || 'application/json',
      'x-replay-source': 'recording',
    },
  });
}

function unrecordedApiResponse(method) {
  if (UNRECORDED_MODE === 'bypass') return null;
  // empty-200: keep the app alive. JSON for fetch/XHR; HEAD/OPTIONS get 204.
  if (method === 'OPTIONS' || method === 'HEAD') {
    return new Response(null, {
      status: 204,
      headers: { 'x-replay-source': 'empty' },
    });
  }
  SERVED_EMPTY200++;
  return new Response('{}', {
    status: 200,
    headers: {
      'content-type': 'application/json',
      'x-replay-source': 'empty',
    },
  });
}

const JS_EXT = /\\.(m?js|cjs)$/i;
const CSS_EXT = /\\.css$/i;
const MEDIA_EXT = /\\.(png|jpe?g|gif|svg|webp|avif|ico|woff2?|ttf|otf|eot|wasm|mp4|webm|m4a|mp3|ogg)$/i;

function looksStatic(pathname) {
  return JS_EXT.test(pathname) || CSS_EXT.test(pathname) || MEDIA_EXT.test(pathname);
}

/**
 * Graceful stub for an uncaptured same-origin static asset (a lazy chunk or
 * asset the crawl never recorded). Returns the RIGHT content-type so a missing
 * file does not hard-crash the bundle: empty JS module for *.js, empty CSS for
 * *.css, empty body otherwise.
 */
function staticStub(pathname) {
  if (JS_EXT.test(pathname)) {
    return new Response('export {};\\n', {
      status: 200,
      headers: { 'content-type': 'application/javascript; charset=utf-8' },
    });
  }
  if (CSS_EXT.test(pathname)) {
    return new Response('/* dr-parity replay: uncaptured stylesheet */\\n', {
      status: 200,
      headers: { 'content-type': 'text/css; charset=utf-8' },
    });
  }
  return new Response(null, { status: 200, headers: { 'content-type': 'application/octet-stream' } });
}

/**
 * Serve a same-origin static request from the static file server; on 404 or a
 * network error, fall back to a typed stub so a missing lazy chunk / asset is
 * non-fatal.
 */
async function handleStatic(request, pathname) {
  try {
    const res = await fetch(request);
    if (res && res.status !== 404) return res;
  } catch (err) {
    /* fall through to stub */
  }
  return staticStub(pathname);
}

